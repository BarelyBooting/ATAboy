# run.sh builds and runs these in order, each ending with "N checks, M failed".
# Mutants run with SAT on, where run.sh builds test_read and test_fwupdate
# twice each (with and without the SMART opt-in). This list said two programs
# while run.sh ran three from 0a6cb06 on; a surviving mutant would then have
# been reported as "not run" instead of SURVIVED (fixed in 0.6f3p7).
# test_manual_chs twice: its own run, then "q7-core1" (Q7, core 1's loop).
# Then the descriptor layout twice (the Control API off and on), and, in a
# build with the API (run.sh's default), test_ctl four times (its tests,
# "core1", "core1-confirm", "core1-tui"), test_config_save, ctl_fuzz, and
# ctl_e2e.py, which runs test_ctl, presence_rows.py, and test_ctl built without
# the jumpers (test_ctl_nojumpers, the last).
PROGRAMS = ['test_read', 'test_read_pipelined', 'transcripts', 'test_read_shipping', 'test_fwupdate', 'test_fwupdate_smart', 'test_manual_chs',
            'test_manual_chs', 'test_usb_desc', 'test_pio_timing', 'test_usb_layout0', 'test_usb_layout1',
            'test_ctl', 'test_ctl', 'test_ctl', 'test_ctl', 'test_config_save', 'ctl_fuzz', 'test_ctl', 'presence_rows',
            'test_ctl_nojumpers']


TIMEOUT_S = 900


def run_tests(srcdir, outdir):
    """run.sh on srcdir; None if it did not finish within TIMEOUT_S.

    On Windows subprocess.run kills only the direct child (sh) on a timeout,
    and the test program sh started keeps the output pipes open, so the
    following communicate() waited for it, for ever if it hung (review C
    MED-1, reproduced: 40 s for a 3 s timeout). So: Popen, and on a timeout
    kill the whole tree (taskkill /F /T on Windows, the process group
    elsewhere), then reap.
    """
    env = dict(os.environ, OUT=outdir)
    posix = os.name != 'nt'
    p = subprocess.Popen(['sh', os.path.join(HERE, 'run.sh'), srcdir], env=env,
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                         encoding='utf-8', errors='replace',    # the TUI's box characters are UTF-8
                         start_new_session=posix)
    try:
        out, err = p.communicate(timeout=TIMEOUT_S)
    except subprocess.TimeoutExpired:
        if posix:
            import signal
            try: os.killpg(p.pid, signal.SIGKILL)
            except OSError: p.kill()
        else:
            subprocess.run(['taskkill', '/F', '/T', '/PID', str(p.pid)], capture_output=True)   # sh AND what it started
        p.communicate()         # the pipes are closed now, so this returns
        return None
    return subprocess.CompletedProcess(p.args, p.returncode, out, err)


def main():
    global TIMEOUT_S
    args = sys.argv[1:]
    if '--timeout' in args:
        i = args.index('--timeout'); TIMEOUT_S = int(args[i + 1]); del args[i:i + 2]
    sys.argv[1:] = args
    base = run_tests(SRC, tempfile.mkdtemp(prefix='ataboy-host-'))
    if base is None:
        print('the unmutated sources timed out'); return 2
    last = ' / '.join(l for l in base.stdout.splitlines() if 'checks,' in l) or base.stderr[-500:]
    print(f'unmutated: rc={base.returncode}  {last}')
    if base.returncode != 0:
        print('the unmutated sources must pass first'); return 2
    nsum = sum(1 for l in base.stdout.splitlines() if 'checks,' in l)
    if nsum != len(PROGRAMS):
        # PROGRAMS is indexed by the summary lines seen; a program added to
        # run.sh without it would mislabel a crash (review C LOW-3).
        print(f'run.sh printed {nsum} summary lines but PROGRAMS names {len(PROGRAMS)}: edit PROGRAMS'); return 2
    bad_setup, survived, killed, crashed, timed_out = [], [], [], [], []
    words = sys.argv[1:]
    shard = None
    if len(words) >= 2 and words[0] == '--shard':       # --shard i/n: every n-th chosen mutant from i
        shard = tuple(int(x) for x in words[1].split('/'))
        words = words[2:]
    chosen = [m for m in MUTANTS if not words or any(w in m[0] for w in words)]
    if shard:
        chosen = chosen[shard[0]::shard[1]]
    for name, fname, old, new in chosen:
        tmp = tempfile.mkdtemp(prefix='ataboy-mut-')
        src = os.path.join(tmp, 'src')
        shutil.copytree(SRC, src)
        path = os.path.join(src, fname)
        text = open(path, 'rb').read().decode('utf-8').replace('\r\n', '\n')
        if text.count(old) != 1:
            bad_setup.append((name, f'text found {text.count(old)} times'))
            print(f'NOT APPLIED  {name}'); continue
        open(path, 'wb').write(text.replace(old, new).encode('utf-8'))
        p = run_tests(src, os.path.join(tmp, 'out'))
        if p is None:
            # A hang is not a detection (review C MED-2): its own bucket, never
            # in "killed". Rerun it alone; it counts only if a check then fails.
            timed_out.append(name)
            print(f'TIMEOUT      {name}\n             no result after {TIMEOUT_S} s (not counted as killed)')
            shutil.rmtree(tmp, ignore_errors=True); continue
        out = p.stdout.strip().splitlines()
        sums = [l for l in out if 'checks,' in l]
        summary = ' / '.join(sums)
        reported_failure = any(not l.endswith(' 0 failed') for l in sums)
        if p.returncode != 0 and not reported_failure:
            # run.sh stopped before every program reported. If the next one
            # was built, it crashed before its summary (a segfault, say): the
            # tests caught it, just not gracefully, so it counts as killed.
            # If it was not built, the mutant broke the build: not run.
            nxt = PROGRAMS[len(sums)] if len(sums) < len(PROGRAMS) else None
            built = nxt and any(os.path.exists(os.path.join(tmp, 'out', nxt + x)) for x in ('', '.exe'))
            if built:
                killed.append(name)
                crashed.append(name)
                last = (p.stdout.strip().splitlines() or ['?'])[-1][:150]
                print(f'KILLED       {name}\n             {nxt} crashed: {(p.stderr.strip().splitlines() or ["?"])[-1][:150]} (last output: {last})')
            else:
                bad_setup.append((name, 'did not build: ' + (p.stderr.strip().splitlines() or ['?'])[-1]))
                print(f'NO RESULT    {name}')
            shutil.rmtree(tmp, ignore_errors=True); continue
        if p.returncode == 0 and len(sums) != len(PROGRAMS):
            bad_setup.append((name, f'{len(sums)} of {len(PROGRAMS)} test programs reported'))
            print(f'NO RESULT    {name}'); continue
        if p.returncode != 0:
            killed.append(name)
            first = next((l for l in out if l.startswith('FAIL')), '')
            print(f'KILLED       {name}\n             {summary}; first: {first[:150]}')
        else:
            survived.append(name)
            print(f'SURVIVED     {name}  ({summary})')
        shutil.rmtree(tmp, ignore_errors=True)
    print(f'\n{len(killed)} killed, {len(survived)} survived, {len(timed_out)} timed out (not kills), {len(bad_setup)} not run, of {len(chosen)}'
          + (f' (filtered from {len(MUTANTS)})' if words or shard else '')
          + (f', shard {shard[0]}/{shard[1]}' if shard else ''))
    # A kill by a crash or a timeout (no summary line) is a kill, but not by a
    # failed check: listed apart, so each can be looked at.
    print(f'{len(killed) - len(crashed)} killed by a failed check, {len(crashed)} crash-only')
    for n in crashed:
        print(f'  crash-only: {n}')
    for n in timed_out:
        print(f'  timeout: {n}')
    for n, why in bad_setup:
        print(f'  not run: {n}: {why}')
    return 0 if not survived and not bad_setup and not timed_out else 1


if __name__ == '__main__':
    sys.exit(main())
